
-- SISTEM AKUNTANSI MODAL DAN PRIVE
-- Database: PostgreSQL (Supabase)

CREATE TABLE IF NOT EXISTS public.transaksi_ekuitas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tanggal DATE NOT NULL,
    jenis_transaksi VARCHAR(30) NOT NULL
        CHECK (
            jenis_transaksi IN (
                'modal_awal',
                'tambahan_modal',
                'prive',
                'laba_bersih',
                'rugi_bersih'
            )
        ),
    keterangan TEXT NOT NULL,
    jumlah NUMERIC(18,2) NOT NULL CHECK (jumlah > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_transaksi_ekuitas_tanggal
ON public.transaksi_ekuitas (tanggal);

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_updated_at_ekuitas
ON public.transaksi_ekuitas;

CREATE TRIGGER trg_updated_at_ekuitas
BEFORE UPDATE ON public.transaksi_ekuitas
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at();

-- Laporan perubahan ekuitas berdasarkan periode.
-- Nilai modal awal periode = akumulasi saldo transaksi
-- sebelum tanggal awal periode.

CREATE OR REPLACE FUNCTION public.laporan_perubahan_ekuitas(
    p_tanggal_awal DATE,
    p_tanggal_akhir DATE
)
RETURNS TABLE (
    modal_awal_periode NUMERIC,
    tambahan_modal NUMERIC,
    laba_bersih NUMERIC,
    rugi_bersih NUMERIC,
    total_prive NUMERIC,
    kenaikan_penurunan_ekuitas NUMERIC,
    modal_akhir NUMERIC
)
LANGUAGE sql
STABLE
AS $$
    WITH saldo AS (
        SELECT
            COALESCE(SUM(
                CASE
                    WHEN jenis_transaksi IN (
                        'modal_awal',
                        'tambahan_modal',
                        'laba_bersih'
                    ) THEN jumlah
                    WHEN jenis_transaksi IN (
                        'prive',
                        'rugi_bersih'
                    ) THEN -jumlah
                    ELSE 0
                END
            ) FILTER (WHERE tanggal < p_tanggal_awal), 0)
                AS saldo_sebelumnya,

            COALESCE(SUM(jumlah) FILTER (
                WHERE tanggal BETWEEN p_tanggal_awal
                                  AND p_tanggal_akhir
                  AND jenis_transaksi = 'tambahan_modal'
            ), 0) AS tambahan,

            COALESCE(SUM(jumlah) FILTER (
                WHERE tanggal BETWEEN p_tanggal_awal
                                  AND p_tanggal_akhir
                  AND jenis_transaksi = 'laba_bersih'
            ), 0) AS laba,

            COALESCE(SUM(jumlah) FILTER (
                WHERE tanggal BETWEEN p_tanggal_awal
                                  AND p_tanggal_akhir
                  AND jenis_transaksi = 'rugi_bersih'
            ), 0) AS rugi,

            COALESCE(SUM(jumlah) FILTER (
                WHERE tanggal BETWEEN p_tanggal_awal
                                  AND p_tanggal_akhir
                  AND jenis_transaksi = 'prive'
            ), 0) AS prive
        FROM public.transaksi_ekuitas
    )
    SELECT
        saldo_sebelumnya,
        tambahan,
        laba,
        rugi,
        prive,
        tambahan + laba - rugi - prive,
        saldo_sebelumnya + tambahan + laba - rugi - prive
    FROM saldo;
$$;

-- Aplikasi memakai Supabase tanpa login, sehingga data transaksi dapat
-- dibaca dan diubah oleh siapa pun yang mengetahui URL dan publishable key.
ALTER TABLE public.transaksi_ekuitas ENABLE ROW LEVEL SECURITY;

GRANT USAGE ON SCHEMA public TO anon;
GRANT SELECT, INSERT, UPDATE, DELETE
ON public.transaksi_ekuitas TO anon;
GRANT USAGE, SELECT
ON SEQUENCE public.transaksi_ekuitas_id_seq TO anon;
GRANT EXECUTE
ON FUNCTION public.laporan_perubahan_ekuitas(DATE, DATE) TO anon;

DROP POLICY IF EXISTS "Akses publik transaksi ekuitas"
ON public.transaksi_ekuitas;
CREATE POLICY "Akses publik transaksi ekuitas"
ON public.transaksi_ekuitas
FOR ALL TO anon
USING (true)
WITH CHECK (true);

