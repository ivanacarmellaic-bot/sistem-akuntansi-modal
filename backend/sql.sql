            FROM public.transaksi_ekuitas
            WHERE jenis_transaksi IN ('modal_awal', 'tambahan_modal')
            ON CONFLICT (legacy_id) DO NOTHING
        $migration$ USING v_pemilik_id;

        EXECUTE $migration$
            INSERT INTO public.prive
                (pemilik_id, tanggal, keterangan, jumlah,
                 legacy_id, created_at, updated_at)
            SELECT $1, tanggal, keterangan, jumlah, id,
                   created_at, updated_at
            FROM public.transaksi_ekuitas
            WHERE jenis_transaksi = 'prive'
            ON CONFLICT (legacy_id) DO NOTHING
        $migration$ USING v_pemilik_id;

        EXECUTE $migration$
            INSERT INTO public.laba_rugi
                (pemilik_id, tanggal, jenis_laba_rugi, keterangan, jumlah,
                 legacy_id, created_at, updated_at)
            SELECT $1, tanggal, jenis_transaksi, keterangan, jumlah, id,
                   created_at, updated_at
            FROM public.transaksi_ekuitas
            WHERE jenis_transaksi IN ('laba_bersih', 'rugi_bersih')
            ON CONFLICT (legacy_id) DO NOTHING
        $migration$ USING v_pemilik_id;
    END IF;
END;
$$;

