-- SISTEM AKUNTANSI MODAL DAN PRIVE
-- Empat entitas: pemilik, modal, prive, dan laba_rugi.

CREATE TABLE IF NOT EXISTS public.pemilik (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_pemilik VARCHAR(150) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.modal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pemilik_id BIGINT NOT NULL REFERENCES public.pemilik(id),
    tanggal DATE NOT NULL,
    jenis_modal VARCHAR(30) NOT NULL
        CHECK (jenis_modal IN ('modal_awal', 'tambahan_modal')),
    keterangan VARCHAR(500) NOT NULL,
    jumlah NUMERIC(18,2) NOT NULL CHECK (jumlah > 0),
    legacy_id BIGINT UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.prive (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pemilik_id BIGINT NOT NULL REFERENCES public.pemilik(id),
    tanggal DATE NOT NULL,
    keterangan VARCHAR(500) NOT NULL,
    jumlah NUMERIC(18,2) NOT NULL CHECK (jumlah > 0),
    legacy_id BIGINT UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.laba_rugi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pemilik_id BIGINT NOT NULL REFERENCES public.pemilik(id),
    tanggal DATE NOT NULL,
    jenis_laba_rugi VARCHAR(30) NOT NULL
        CHECK (jenis_laba_rugi IN ('laba_bersih', 'rugi_bersih')),
    keterangan VARCHAR(500) NOT NULL,
    jumlah NUMERIC(18,2) NOT NULL CHECK (jumlah > 0),
    legacy_id BIGINT UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO public.pemilik (nama_pemilik)
VALUES ('Pemilik Perusahaan')
ON CONFLICT (nama_pemilik) DO NOTHING;

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_updated_at_modal ON public.modal;
CREATE TRIGGER trg_updated_at_modal
BEFORE UPDATE ON public.modal
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS trg_updated_at_prive ON public.prive;
CREATE TRIGGER trg_updated_at_prive
BEFORE UPDATE ON public.prive
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS trg_updated_at_laba_rugi ON public.laba_rugi;
CREATE TRIGGER trg_updated_at_laba_rugi
BEFORE UPDATE ON public.laba_rugi
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE INDEX IF NOT EXISTS idx_modal_tanggal
ON public.modal (tanggal);
CREATE INDEX IF NOT EXISTS idx_prive_tanggal
ON public.prive (tanggal);
CREATE INDEX IF NOT EXISTS idx_laba_rugi_tanggal
ON public.laba_rugi (tanggal);

