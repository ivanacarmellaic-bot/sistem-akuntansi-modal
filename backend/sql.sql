    v_pemilik_id BIGINT;
BEGIN
    SELECT id INTO v_pemilik_id
    FROM public.pemilik
    WHERE nama_pemilik = 'Pemilik Perusahaan';

    IF to_regclass('public.transaksi_ekuitas') IS NOT NULL
       AND EXISTS (
           SELECT 1
           FROM pg_class
           WHERE oid = to_regclass('public.transaksi_ekuitas')
             AND relkind = 'r'
       ) THEN
        EXECUTE $migration$
            INSERT INTO public.modal
                (pemilik_id, tanggal, jenis_modal, keterangan, jumlah,
                 legacy_id, created_at, updated_at)
            SELECT $1, tanggal, jenis_transaksi, keterangan, jumlah, id,
