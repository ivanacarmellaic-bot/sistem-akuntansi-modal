-- View gabungan agar daftar transaksi lama tetap dapat dibaca oleh aplikasi.
CREATE OR REPLACE VIEW public.transaksi_ekuitas
WITH (security_invoker = true)
AS
    SELECT
        'modal:' || id::text AS id,
        tanggal,
        jenis_modal AS jenis_transaksi,
        keterangan,
        jumlah,
        created_at,
        updated_at
    FROM public.modal
    UNION ALL
    SELECT
        'prive:' || id::text,
        tanggal,
        'prive'::VARCHAR(30),
        keterangan,
        jumlah,
        created_at,
        updated_at
    FROM public.prive
    UNION ALL
    SELECT
        'laba_rugi:' || id::text,
        tanggal,
        jenis_laba_rugi,
        keterangan,
        jumlah,
        created_at,
        updated_at
    FROM public.laba_rugi;

CREATE OR REPLACE FUNCTION public.simpan_transaksi_ekuitas(
    p_id TEXT,
    p_tanggal DATE,
    p_jenis_transaksi TEXT,
    p_keterangan TEXT,
    p_jumlah NUMERIC
)
RETURNS TEXT
LANGUAGE plpgsql
AS $$
DECLARE
    v_entitas TEXT;
    v_id BIGINT;
    v_entitas_baru TEXT;
    v_pemilik_id BIGINT;
    v_rows INTEGER;
    v_id_baru BIGINT;
BEGIN
    IF p_jenis_transaksi IN ('modal_awal', 'tambahan_modal') THEN
        v_entitas_baru := 'modal';
    ELSIF p_jenis_transaksi = 'prive' THEN
        v_entitas_baru := 'prive';
    ELSIF p_jenis_transaksi IN ('laba_bersih', 'rugi_bersih') THEN
        v_entitas_baru := 'laba_rugi';
    ELSE
        RAISE EXCEPTION 'Jenis transaksi tidak valid.';
    END IF;

    IF p_id IS NOT NULL THEN
        v_entitas := split_part(p_id, ':', 1);
        IF v_entitas NOT IN ('modal', 'prive', 'laba_rugi')
           OR split_part(p_id, ':', 2) !~ '^[1-9][0-9]*$'
           OR split_part(p_id, ':', 3) <> '' THEN
            RAISE EXCEPTION 'ID transaksi tidak valid.';
        END IF;
        v_id := split_part(p_id, ':', 2)::BIGINT;

        IF v_entitas = 'modal' THEN
            DELETE FROM public.modal WHERE id = v_id;
        ELSIF v_entitas = 'prive' THEN
            DELETE FROM public.prive WHERE id = v_id;
        ELSE
            DELETE FROM public.laba_rugi WHERE id = v_id;
        END IF;

        GET DIAGNOSTICS v_rows = ROW_COUNT;
        IF v_rows = 0 THEN
            RAISE EXCEPTION 'Transaksi tidak ditemukan.';
        END IF;
    END IF;

    SELECT id INTO v_pemilik_id
    FROM public.pemilik
    WHERE nama_pemilik = 'Pemilik Perusahaan';

    IF v_entitas_baru = 'modal' THEN
        INSERT INTO public.modal
            (pemilik_id, tanggal, jenis_modal, keterangan, jumlah)
        VALUES
            (v_pemilik_id, p_tanggal, p_jenis_transaksi, p_keterangan, p_jumlah)
        RETURNING id INTO v_id_baru;
    ELSIF v_entitas_baru = 'prive' THEN
        INSERT INTO public.prive (pemilik_id, tanggal, keterangan, jumlah)
        VALUES (v_pemilik_id, p_tanggal, p_keterangan, p_jumlah)
        RETURNING id INTO v_id_baru;
    ELSE
        INSERT INTO public.laba_rugi
            (pemilik_id, tanggal, jenis_laba_rugi, keterangan, jumlah)
        VALUES
            (v_pemilik_id, p_tanggal, p_jenis_transaksi, p_keterangan, p_jumlah)
        RETURNING id INTO v_id_baru;
    END IF;

    RETURN v_entitas_baru || ':' || v_id_baru::TEXT;
END;
$$;

CREATE OR REPLACE FUNCTION public.hapus_transaksi_ekuitas(p_id TEXT)
RETURNS BOOLEAN
LANGUAGE plpgsql
AS $$
DECLARE
    v_entitas TEXT := split_part(p_id, ':', 1);
    v_id BIGINT;
    v_rows INTEGER;
BEGIN
    IF v_entitas NOT IN ('modal', 'prive', 'laba_rugi')
       OR split_part(p_id, ':', 2) !~ '^[1-9][0-9]*$'
       OR split_part(p_id, ':', 3) <> '' THEN
        RAISE EXCEPTION 'ID transaksi tidak valid.';
    END IF;
    v_id := split_part(p_id, ':', 2)::BIGINT;

    IF v_entitas = 'modal' THEN
        DELETE FROM public.modal WHERE id = v_id;
    ELSIF v_entitas = 'prive' THEN
        DELETE FROM public.prive WHERE id = v_id;
    ELSE
        DELETE FROM public.laba_rugi WHERE id = v_id;
    END IF;

    GET DIAGNOSTICS v_rows = ROW_COUNT;
    RETURN v_rows > 0;
END;
$$;

CREATE OR REPLACE FUNCTION public.laporan_perubahan_ekuitas(
    p_tanggal_awal DATE,
    p_tanggal_akhir DATE
)
RETURNS TABLE (
    modal_awal_periode NUMERIC,
    tambahan_modal NUMERIC,
    laba_bersih NUMERIC,
    rugi_bersih NUMERIC,
    total_prive NUMERIC,
    kenaikan_penurunan_ekuitas NUMERIC,
    modal_akhir NUMERIC
)
LANGUAGE sql
STABLE
AS $$
    WITH transaksi AS (
        SELECT tanggal, jenis_transaksi, jumlah
        FROM public.transaksi_ekuitas
    ),
    saldo AS (
        SELECT
            COALESCE(SUM(
                CASE
                    WHEN jenis_transaksi IN (
                        'modal_awal', 'tambahan_modal', 'laba_bersih'
                    ) THEN jumlah
                    WHEN jenis_transaksi IN ('prive', 'rugi_bersih') THEN -jumlah
                    ELSE 0
                END
            ) FILTER (WHERE tanggal < p_tanggal_awal), 0) AS saldo_sebelumnya,
            COALESCE(SUM(jumlah) FILTER (
                WHERE tanggal BETWEEN p_tanggal_awal AND p_tanggal_akhir
                  AND jenis_transaksi = 'tambahan_modal'
            ), 0) AS tambahan,
            COALESCE(SUM(jumlah) FILTER (
                WHERE tanggal BETWEEN p_tanggal_awal AND p_tanggal_akhir
                  AND jenis_transaksi = 'laba_bersih'
            ), 0) AS laba,
            COALESCE(SUM(jumlah) FILTER (
                WHERE tanggal BETWEEN p_tanggal_awal AND p_tanggal_akhir
                  AND jenis_transaksi = 'rugi_bersih'
            ), 0) AS rugi,
            COALESCE(SUM(jumlah) FILTER (
                WHERE tanggal BETWEEN p_tanggal_awal AND p_tanggal_akhir
                  AND jenis_transaksi = 'prive'
            ), 0) AS prive
        FROM transaksi
    )
    SELECT
        saldo_sebelumnya,
        tambahan,
        laba,
        rugi,
        prive,
        tambahan + laba - rugi - prive,
        saldo_sebelumnya + tambahan + laba - rugi - prive
    FROM saldo;
$$;

